"""Item reference-number generation (PRD Section 10, CD-01).

``app/domain/numbering.py`` does not exist in this codebase; the register code
is generated by ``app.services.items.next_item_code``, so that is what is
tested here. A database session is needed purely for the row count.
"""

from __future__ import annotations

import pytest

from app.models.compliance import ComplianceItem
from app.models.org import Category
from app.services.items import next_item_code


def _add_item(db, code: str) -> None:
    db.add(ComplianceItem(item_code=code, name=f"Item {code}"))


def test_first_code_for_an_uncategorised_item(db) -> None:
    assert next_item_code(db, None) == "CMP-0001"


def test_prefix_is_the_first_three_letters_of_the_category(db) -> None:
    assert next_item_code(db, Category(name="Factory Licence")) == "FAC-0001"


def test_non_letters_are_stripped_before_taking_the_prefix(db) -> None:
    assert next_item_code(db, Category(name="ISO 14001")) == "ISO-0001"
    assert next_item_code(db, Category(name="PESO/Explosives")) == "PES-0001"


def test_a_short_category_name_yields_a_short_prefix(db) -> None:
    # A quirk worth pinning: fewer than three letters means a shorter prefix.
    assert next_item_code(db, Category(name="A1")) == "A-0001"


def test_a_numeric_only_category_name_falls_back_to_the_default_prefix(db) -> None:
    assert next_item_code(db, Category(name="14001")) == "CMP-0001"


def test_an_unnamed_category_falls_back_to_the_default_prefix(db) -> None:
    assert next_item_code(db, Category(name="")) == "CMP-0001"


def test_codes_are_zero_padded_to_four_digits(db) -> None:
    _add_item(db, "CMP-0001")
    _add_item(db, "CMP-0002")
    db.flush()
    assert next_item_code(db, None) == "CMP-0003"


def test_the_sequence_is_global_rather_than_per_category(db) -> None:
    # The count is over the whole register, so a new category continues the
    # same sequence instead of restarting at 1.
    _add_item(db, "CMP-0001")
    _add_item(db, "FAC-0002")
    db.flush()
    assert next_item_code(db, Category(name="Factory Licence")) == "FAC-0003"


@pytest.mark.parametrize("count", [9, 99, 999])
def test_padding_holds_across_magnitudes(db, count: int) -> None:
    for index in range(count):
        _add_item(db, f"CMP-{index + 1:04d}")
    db.flush()
    assert next_item_code(db, None) == f"CMP-{count + 1:04d}"
