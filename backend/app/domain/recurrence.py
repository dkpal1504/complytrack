"""Recurrence engine (RT-03): generate the next cycle of a periodic obligation.

On closure of one instance the next one is derived from the rule — monthly on a
specific day, quarterly, half-yearly, annual, financial-year-aligned, or an
"N months from last done" interval.
"""

from __future__ import annotations

import calendar
from datetime import date

from app.domain.dates import add_months, add_years, end_of_financial_year, financial_year_label
from app.domain.enums import RecurrenceKind


def _clamp_day(year: int, month: int, day: int) -> date:
    return date(year, month, min(day, calendar.monthrange(year, month)[1]))


def next_due_date(
    rule: str,
    from_date: date,
    *,
    day: int | None = None,
    interval_months: int | None = None,
    fy_start_month: int = 4,
) -> date | None:
    """The due date of the cycle that follows ``from_date``.

    ``from_date`` is normally the due date of the cycle being closed.
    """
    if rule == RecurrenceKind.NONE:
        return None

    if rule == RecurrenceKind.MONTHLY:
        target_month = add_months(from_date.replace(day=1), 1)
        return _clamp_day(target_month.year, target_month.month, day or from_date.day)

    if rule == RecurrenceKind.QUARTERLY:
        target = add_months(from_date, 3)
        return _clamp_day(target.year, target.month, day) if day else target

    if rule == RecurrenceKind.HALF_YEARLY:
        target = add_months(from_date, 6)
        return _clamp_day(target.year, target.month, day) if day else target

    if rule == RecurrenceKind.ANNUAL:
        target = add_years(from_date, 1)
        return _clamp_day(target.year, target.month, day) if day else target

    if rule == RecurrenceKind.FY_ANNUAL:
        # Next financial-year end after the current cycle.
        return add_years(end_of_financial_year(from_date, fy_start_month), 1)

    if rule == RecurrenceKind.INTERVAL:
        months = interval_months or 12
        target = add_months(from_date, months)
        return _clamp_day(target.year, target.month, day) if day else target

    raise ValueError(f"Unknown recurrence rule: {rule!r}")


def period_for(rule: str, due_date: date, *, fy_start_month: int = 4) -> tuple[date, date]:
    """The (period_start, period_end) window that a due date closes out."""
    if rule == RecurrenceKind.MONTHLY:
        start = due_date.replace(day=1)
        end = due_date.replace(day=calendar.monthrange(due_date.year, due_date.month)[1])
        return start, end

    if rule == RecurrenceKind.QUARTERLY:
        start = add_months(due_date.replace(day=1), -2)
        end = due_date.replace(day=calendar.monthrange(due_date.year, due_date.month)[1])
        return start, end

    if rule == RecurrenceKind.HALF_YEARLY:
        start = add_months(due_date.replace(day=1), -5)
        end = due_date.replace(day=calendar.monthrange(due_date.year, due_date.month)[1])
        return start, end

    if rule == RecurrenceKind.FY_ANNUAL:
        end = end_of_financial_year(due_date, fy_start_month)
        start = add_months(end.replace(day=1), -11)
        return start, end

    if rule in (RecurrenceKind.ANNUAL, RecurrenceKind.INTERVAL):
        end = due_date
        # Window runs from the day after the previous anniversary.
        start = add_years(due_date, -1).replace(day=1)
        return start, end

    return due_date, due_date


def cycle_label(rule: str, due_date: date, *, fy_start_month: int = 4) -> str:
    """Human label for a cycle, e.g. 'FY2026-27', 'Jun-2026', 'Q1 FY2026-27'."""
    if rule == RecurrenceKind.MONTHLY:
        return due_date.strftime("%b-%Y")

    if rule == RecurrenceKind.QUARTERLY:
        fy = financial_year_label(due_date, fy_start_month)
        # Indian FY quarters: Apr-Jun, Jul-Sep, Oct-Dec, Jan-Mar.
        fy_start_year = int(fy[2:6])
        if due_date.month >= fy_start_month:
            quarter = (due_date.month - fy_start_month) // 3 + 1
        else:
            quarter = (due_date.month + 12 - fy_start_month) // 3 + 1
        return f"Q{quarter} {fy}"

    if rule == RecurrenceKind.HALF_YEARLY:
        fy = financial_year_label(due_date, fy_start_month)
        half = 1 if due_date.month >= 4 and due_date.month <= 9 else 2
        return f"H{half} {fy}"

    if rule in (RecurrenceKind.ANNUAL, RecurrenceKind.FY_ANNUAL):
        return financial_year_label(due_date, fy_start_month)

    if rule == RecurrenceKind.INTERVAL:
        return due_date.strftime("%d-%b-%Y")

    return due_date.strftime("%d-%b-%Y")


def cycles_between(
    rule: str,
    start: date,
    end: date,
    *,
    day: int | None = None,
    interval_months: int | None = None,
    fy_start_month: int = 4,
    limit: int = 500,
) -> list[date]:
    """Every due date generated by ``rule`` in [start, end] — used by the calendar."""
    if rule == RecurrenceKind.NONE:
        return [start] if start <= end else []

    out: list[date] = []
    cursor = start
    while cursor <= end and len(out) < limit:
        out.append(cursor)
        nxt = next_due_date(
            rule, cursor, day=day, interval_months=interval_months, fy_start_month=fy_start_month
        )
        if nxt is None or nxt <= cursor:
            break
        cursor = nxt
    return out
